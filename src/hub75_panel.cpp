/* ── GFX 상태 ── */
static int16_t  gx   = 0;
static int16_t  gy   = 0;
static u16      gcol = 0xFFFF;
static uint8_t  gsz  = 1;

void setCursor(int16_t x, int16_t y) { gx = x; gy = y; }
void setColor(u16 c)                  { gcol = c; }
void setSize(uint8_t s)               { gsz = s ? s : 1; }

/* ── drawChar / printStr ── */
static void drawPx(int16_t x, int16_t y, u16 c) {
    if (x < 0 || x >= MATRIX_W || y < 0 || y >= MATRIX_H) return;
    uint8_t r = (uint8_t)((c >> 8) & 0xF8); r = (uint8_t)(r | (r >> 5));
    uint8_t g = (uint8_t)((c >> 3) & 0xFC); g = (uint8_t)(g | (g >> 6));
    uint8_t b = (uint8_t)(c << 3);           b = (uint8_t)(b | (b >> 5));
    setPixel((u16)x, (u16)y, r, g, b);
}

void drawChar(int16_t x, int16_t y, char c, u16 col, uint8_t sz) {
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *f = kFont[(uint8_t)c - 0x20];
    for (int8_t cx = 0; cx < 5; cx++) {
        uint8_t line = f[cx];
        for (int8_t row = 0; row < 7; row++, line >>= 1) {
            if (line & 1) {
                if (sz == 1) drawPx(x + cx, y + row, col);
                else for (int i = 0; i < sz; i++)
                     for (int j = 0; j < sz; j++)
                         drawPx(x + cx*sz + i, y + row*sz + j, col);
            }
        }
    }
}

void printStr(const char *s) {
    while (s && *s) {
        char c = *s++;
        if (c == '\n') { gy += gsz * 8; gx = 0; continue; }
        if (c == '\r') continue;
        drawChar(gx, gy, c, gcol, gsz);
        gx += gsz * 6;
    }
}
